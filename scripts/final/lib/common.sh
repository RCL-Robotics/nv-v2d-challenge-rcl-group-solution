# common.sh: sourced by every scripts/final/*.sh. Options shared by all scripts:
#   --dry-run      print the commands (the "plan") and execute nothing
#   --site FILE    a site file (copy of scripts/final/site.env.example) with this machine's paths
#   -h, --help     the script's usage
# Without --site, the variables come from the environment, and unset ones default to the training server's layout
# (ROOT_ME=/root/autodl-tmp/haoran.zhang), where every record path is real.
# A real run writes its plan to $V2D_WORK/logs/<script>_<time>.sh and runs it with bash -euo pipefail.
set -u -o pipefail

FINAL_LIB=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
FINAL_DIR=$(dirname "$FINAL_LIB")
REPO=$(cd "$FINAL_DIR/../.." && pwd)
FC_DIR=$REPO/robotic_grounding/flash_chord
TR=$FC_DIR/scripts/track2
SCRIPT_NAME=$(basename "$0" .sh)
GITHUB_REPO=https://github.com/Beat-in-our-hearts/nv-v2d-challenge-codebase

die() { echo "[final] ERROR: $*" >&2; exit 1; }

DRY=0; SITE=""; REST=()
final_init() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --dry-run) DRY=1 ;;
      --site) SITE=${2:?--site needs a file}; shift ;;
      --site=*) SITE=${1#--site=} ;;
      -h|--help) usage; exit 0 ;;
      *) REST+=("$1") ;;
    esac
    shift
  done
  if [ -n "$SITE" ]; then
    [ -f "$SITE" ] || die "site file $SITE not found"
    set -a; # shellcheck disable=SC1090
    source "$SITE"; set +a
  fi
  : "${ROOT_ME:=/root/autodl-tmp/haoran.zhang}"
  : "${ROOT_ZX:=/root/autodl-tmp/zuxing.lu}"
  : "${ROOT_HAN:=/root/autodl-tmp/han.zhou}"
  : "${V2D_WORK:=$ROOT_ME/v2d_final_work}"
  : "${FC_PYTHON:=$ROOT_ME/conda_envs/flashchord/bin/python}"
  : "${KIT_PYTHON:=$ROOT_ME/conda_envs/v2dkit/bin/python}"
  : "${RETARGET_PYTHON:=$ROOT_ME/conda_envs/v2d/bin/python}"
  : "${V2D_RUNTIME:=$ROOT_ME/code/video_to_data_8c778f9/robotic_grounding/flash_chord}"
  : "${V2D_KIT:=$ROOT_ME/v2d_submission_kit_src/v2d_submission_kit}"
  : "${V2D_DATA:=$ROOT_ME/data/video_to_data_challenge}"
  : "${T1_MOTION:=$ROOT_ME/data/human_motion_data}"
  : "${T1_RUNS:=$ROOT_ME/fc_runs}"
  : "${T1_EXPORTS:=$ROOT_ME/transfer/t1best_20261026/payload/exports}"
  : "${T1_ZX_RUNS:=$ROOT_ZX/runs/2026-10-14-patience-runin}"   # the record's <RUNS>/runin*/epNN (teammate chains)
  : "${ZX_KIT_PYTHON:=$ROOT_ZX/envs/kit/bin/python}"            # Zuxing Lu's G2 input-builder env
  : "${GPUS:=0}"
  : "${REQUIRE_IDLE_GPU:=0}"
  : "${LFS_FROM:=}"
  if [ -z "${PLAN_PYTHON:-}" ]; then
    if [ -x "$FC_PYTHON" ]; then PLAN_PYTHON=$FC_PYTHON; else PLAN_PYTHON=$(command -v python3 || true); fi
  fi
  [ -n "$PLAN_PYTHON" ] || die "no python found: set PLAN_PYTHON or FC_PYTHON"
  PLAN_PY=$PLAN_PYTHON
  REPO_HEAD=$(git -C "$REPO" rev-parse --verify -q HEAD || echo unknown)
  : "${COMMIT_URL:=$GITHUB_REPO/commit/$REPO_HEAD}"
  export ROOT_ME ROOT_ZX ROOT_HAN V2D_WORK FC_PYTHON KIT_PYTHON RETARGET_PYTHON V2D_RUNTIME V2D_KIT V2D_DATA \
    T1_MOTION T1_RUNS T1_EXPORTS T1_ZX_RUNS ZX_KIT_PYTHON GPUS REQUIRE_IDLE_GPU LFS_FROM PLAN_PY REPO_HEAD COMMIT_URL
  [ -n "${ROOT_ZX5090:-}" ] && export ROOT_ZX5090
  [ -n "${ROOT_ZXWS:-}" ] && export ROOT_ZXWS
  return 0
}

# --- plans built in shell: PLAN holds the lines; add = a raw line, addq = one command, shell-quoted
PLAN=""
add() { PLAN+="$*"$'\n'; }
addq() { local s; printf -v s '%q ' "$@"; PLAN+="${s% }"$'\n'; }
plan_header() {
  add "# $*"
  add "# generated by scripts/final/$SCRIPT_NAME.sh at commit $REPO_HEAD"
  addq FINAL_LIB="$FINAL_LIB"; addq REPO="$REPO"; addq TR="$TR"; addq PLAN_PY="$PLAN_PY"
  addq FC_PYTHON="$FC_PYTHON"; addq KIT_PYTHON="$KIT_PYTHON"; addq RETARGET_PYTHON="$RETARGET_PYTHON"
  addq V2D_RUNTIME="$V2D_RUNTIME"; addq V2D_KIT="$V2D_KIT"; addq V2D_DATA="$V2D_DATA"; addq V2D_WORK="$V2D_WORK"
  addq ROOT_ME="$ROOT_ME"; addq ROOT_ZX="$ROOT_ZX"
  add 'export FINAL_LIB PLAN_PY FC_PYTHON KIT_PYTHON V2D_KIT V2D_DATA'
  add 'source "$FINAL_LIB/helpers.sh"'
}

# run_plan LABEL < plan text: print it (--dry-run) or write it to $V2D_WORK/logs and run it
run_plan() {
  local label=$1 plan f
  plan=$(cat)
  if [ "$DRY" = 1 ]; then
    printf '# ===== dry run of %s: printed, not executed =====\n%s\n' "$label" "$plan"
    return 0
  fi
  mkdir -p "$V2D_WORK/logs" || die "cannot create $V2D_WORK/logs"
  f="$V2D_WORK/logs/${label}_$(date +%Y%m%d_%H%M%S)_$$.sh"
  printf '#!/usr/bin/env bash\nset -euo pipefail\n%s\n' "$plan" > "$f"
  echo "[final] running the plan $f"
  bash "$f"
}

# emit LABEL CMD...: run CMD (a plan generator); only if it succeeds, pass its output to run_plan
emit() {
  local label=$1 out; shift
  out=$("$@") || die "could not build the plan ($*)"
  printf '%s\n' "$out" | run_plan "$label"
}

plan_py() { "$PLAN_PY" -I -B "$FINAL_LIB/plan.py" "$@"; }
